export function resolveThemePalette(appearance = 'dark') {
  return String(appearance || '').trim().toLowerCase() === 'light'
    ? { colors: LIGHT_THEME_COLORS, channels: LIGHT_THEME_COLOR_CHANNELS, specialized: LIGHT_SPECIALIZED_THEME_COLORS }
    : { colors: DARK_THEME_COLORS, channels: DARK_THEME_COLOR_CHANNELS, specialized: DARK_SPECIALIZED_THEME_COLORS }
}

export function buildThemeCssVariables(appearance = 'dark') {
  const resolvedAppearance = String(appearance || '').trim().toLowerCase() === 'light' ? 'light' : 'dark'
  const { colors, channels, specialized } = resolveThemePalette(resolvedAppearance)
  return {
    ...buildColorVariables(colors, channels, specialized, resolvedAppearance),
    ...buildChannelVariables(channels, resolvedAppearance),
  }
}

export function withHexAlpha(color, alpha) {
  const hex = String(color || '').trim()
  const suffix = String(alpha || '').trim().replace(/^#/, '')
  if (!/^#[0-9a-f]{6}$/i.test(hex) || !/^[0-9a-f]{2}$/i.test(suffix)) return hex
  return `${hex}${suffix}`
}
