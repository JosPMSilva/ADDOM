import { createOpenAIResponseMetaEmitter, maybeQueueOpenAIBackgroundTurn } from './chat-stream-openai-round.mjs'
import { runProviderModelRound } from './chat-stream-model-round.mjs'
import { preparePreCallRoundContext } from './chat-stream-precall-round.mjs'
import { runToolCallBatchForRound } from './chat-stream-rounds.mjs'

export async function runSingleStreamRound({
  round = 0,
  loop,
  sender = null,
  wid = 0,
  settings = null,
  history = [],
  rollingUsage = {},
  userMessage = '',
  mode = '',
  permissionMode = 'ask',
  projectFolder = '',
  providerId = '',
  model = '',
  adapterProfile = null,
  promptBudgetProfile = null,
  apiKey = '',
  options = {},
  tools = {},
  activeToolDefinitions = {},
  moaRoles = [],
  moaPolicy = null,
  moaBudgetPolicy = null,
  agentSettings = null,
  modelContext = {},
  continuityRuntime = null,
  providerRuntimeSettings = null,
  activeProjectId = '',
  activeThreadId = '',
  activeTurnId = '',
  activeAssistantMessageId = '',
  openaiHostedToolIds = [],
  providerToolExecutionContext = null,
  toolExecutionMap = {},
  assistantFinalPhase = '',
  assistantCommentaryPhase = '',
  memoryCompressionEnabled = false,
  memoryCompressionThreshold = 0,
  memoryCompressionCooldownMs = 0,
  memoryCompressionMaxPerHour = 0,
  memoryCompressionMinNewLogs = 0,
  repeatedToolCallState = null,
  errorDiagnostics = {},
  turnStartedAt = 0,
  turnOptions = {},
  send = () => {},
  sendNotice = () => {},
  sendTurnState = () => {},
  persistTimelineEvent = () => {},
  emitTurnRuntimeDiagnostics = () => {},
  requestFanoutConfirmation = () => Promise.resolve(null),
  turnToolResults = [],
  turnReasoningSegments = [],
  maxConsecutiveIdenticalToolRounds = 3,
  maxConsecutiveErrorRounds = 3,
  stepSequence = 0,
  consecutiveErrorRounds = 0,
  inspectedFilePathsThisTurn = new Set(),
  hostFullAccessApprovedForTurn = false,
  latestOpenAICompactionId = '',
  moaPreflightRepairRetryUsed = false,
  moaPendingPreflightRepairRetryAttempt = false,
  moaRetryState = null,
  helpers = {},
} = {}) {
  const {
    getApiKey,
    getCachedModelCapabilities,
    buildPreCallContinuityInput,
    compactHistoryForContextWindow,
    applyCompactionIfNeeded,
    estimateHistoryTokens,
    resolveOpenAIThreadContinuation,
    pushUniqueRuntimeValue,
    upsertOpenAIThreadState,
    prepareOpenAIBackgroundTurn,
    createOpenAIBackgroundJob,
    finalizeOpenAIBackgroundJob,
    buildChatUsagePayload,
    emitUsageEvent,
    emitReasoningDone,
    updateOpenAIContinuationContext,
    resolveOpenAIContinuationPersistence,
    recordRepeatedToolCallBatch,
    commitFinalTurn,
    commitFailureTurn,
    finalizeRoundWithoutTools,
    buildAssistantToolUseMessage,
    createStreamWithTools,
    detectTextualApprovalRequestWithoutToolCall,
    touchProjectUsageByThread,
    runPostTurnTasks,
    asTokenCount,
    isAbortError,
    toolBatchHelpers,
  } = helpers

  const precall = await preparePreCallRoundContext({
    history,
    round,
    rollingUsage,
    userMessage,
    turnToolResults,
    turnReasoningSegments,
    errorDiagnostics,
    providerId,
    model: model ?? '',
    adapterProfile,
    promptBudgetProfile,
    activeToolDefinitions,
    providerRuntimeSettings,
    continuityPolicy: continuityRuntime?.policy || null,
    openAIExecutionAuthContext: options?.openAIExecutionAuthContext || null,
    activeProjectId,
    activeThreadId,
    activeTurnId,
    turnOptions,
    apiKey,
    continuityRuntime,
    modelContext,
    loop,
    latestOpenAICompactionId,
    send,
    persistTimelineEvent,
    buildPreCallContinuityInput,
    compactHistoryForContextWindow,
    applyCompactionIfNeeded,
    estimateHistoryTokens,
    resolveOpenAIThreadContinuation,
    pushUniqueRuntimeValue,
    upsertOpenAIThreadState,
  })
  const {
    promptOccupancyEstimateTokens,
    promptOccupancyEstimateConfidence,
    promptOccupancyEstimateMethod,
    openAIContinuityEnabled,
    openAIContinuation,
    shouldStoreOpenAIState,
    currentOpenAIRequestContext: preparedOpenAIRequestContext,
    currentProviderRequestContext: preparedProviderRequestContext,
    toolsetHash,
    systemPromptHash,
    continuitySignature,
    latestOpenAICompactionId: nextLatestOpenAICompactionId,
    commandOnly,
    commandOnlyAssistantText,
  } = precall
  let currentOpenAIRequestContext = preparedOpenAIRequestContext
  let currentProviderRequestContext = preparedProviderRequestContext

  if (commandOnly) {
    finalizeRoundWithoutTools({
      send,
      persistTimelineEvent,
      sendTurnState,
      touchProjectUsageByThread,
      continuityRuntime,
      runPostTurnTasks,
      projectFolder,
      userMessage,
      assistantText: String(commandOnlyAssistantText || '').trim(),
      reasoningSegments: turnReasoningSegments,
      turnToolResults,
      mode,
      memoryCompressionEnabled,
      memoryCompressionThreshold,
      memoryCompressionCooldownMs,
      memoryCompressionMaxPerHour,
      memoryCompressionMinNewLogs,
      providerId,
      apiKey,
      model: model ?? '',
      loop,
      isAbortError,
      threadId: activeThreadId,
      turnId: activeTurnId,
      round,
      stopReason: 'compaction_command',
      assistantMessageId: activeAssistantMessageId,
      assistantPhase: assistantFinalPhase,
    })
    return {
      shouldBreakRoundLoop: true,
      latestOpenAICompactionId: nextLatestOpenAICompactionId,
      currentOpenAIRequestContext,
      currentProviderRequestContext,
      stepSequence,
      consecutiveErrorRounds,
      hostFullAccessApprovedForTurn,
      moaPreflightRepairRetryUsed,
      moaPendingPreflightRepairRetryAttempt,
    }
  }

  const emitOpenAIResponseMeta = createOpenAIResponseMetaEmitter({
    activeProjectId,
    activeThreadId,
    activeTurnId,
    providerId,
    model: model ?? '',
    round,
    providerRuntimeSettings,
    openaiHostedToolIds,
    openAIContinuation,
    shouldStoreOpenAIState,
    toolsetHash,
    systemPromptHash,
    continuitySignature,
    getLastCompactionId: () => nextLatestOpenAICompactionId,
    send,
    persistTimelineEvent,
    upsertOpenAIThreadState,
  })

  const openAIRequestContextForRound = openAIContinuityEnabled && currentOpenAIRequestContext
    ? { ...currentOpenAIRequestContext }
    : undefined

  const backgroundQueued = await maybeQueueOpenAIBackgroundTurn({
    openAIContinuityEnabled,
    activeAssistantMessageId,
    providerId,
    apiKey,
    history,
    options,
    providerRuntimeSettings,
    activeProjectId,
    activeThreadId,
    activeTurnId,
    tools,
    openAIRequestContextForRound,
    projectFolder,
    assistantFinalPhase,
    model: model ?? '',
    emitOpenAIResponseMeta,
    rollingUsage,
    modelContext,
    promptOccupancyEstimateTokens,
    promptOccupancyEstimateConfidence,
    promptOccupancyEstimateMethod,
    round,
    send,
    sendTurnState,
    persistTimelineEvent,
    commitFinalTurn,
    commitFailureTurn,
    emitTurnRuntimeDiagnostics,
    turnReasoningSegments,
    turnToolResults,
    userMessage,
    continuityRuntime,
    mode,
    memoryCompressionEnabled,
    memoryCompressionThreshold,
    memoryCompressionCooldownMs,
    memoryCompressionMaxPerHour,
    memoryCompressionMinNewLogs,
    loop,
    isAbortError,
    runPostTurnTasks,
    touchProjectUsageByThread,
    prepareOpenAIBackgroundTurn,
    createOpenAIBackgroundJob,
    finalizeOpenAIBackgroundJob,
    buildChatUsagePayload,
    emitUsageEvent,
    emitReasoningDone,
    asTokenCount,
  })
  if (backgroundQueued) {
    return {
      shouldBreakRoundLoop: true,
      latestOpenAICompactionId: nextLatestOpenAICompactionId,
      currentOpenAIRequestContext,
      currentProviderRequestContext,
      stepSequence,
      consecutiveErrorRounds,
      hostFullAccessApprovedForTurn,
      moaPreflightRepairRetryUsed,
      moaPendingPreflightRepairRetryAttempt,
    }
  }

  sendTurnState('model_streaming', {
    status: 'model_streaming',
    label: 'model streaming',
    round,
  })
  const modelRound = await runProviderModelRound({
    providerId,
    apiKey,
    history,
    options,
    providerRuntimeSettings,
    activeProjectId,
    activeThreadId,
    activeTurnId,
    activeAssistantMessageId,
    tools,
    openAIRequestContextForRound,
    providerRequestContextForRound: currentProviderRequestContext,
    round,
    model: model ?? '',
    send,
    persistTimelineEvent,
    sendNotice,
    turnStartedAt,
    errorDiagnostics,
    rollingUsage,
    modelContext,
    promptOccupancyEstimateTokens,
    promptOccupancyEstimateConfidence,
    promptOccupancyEstimateMethod,
    turnReasoningSegments,
    openAIContinuityEnabled,
    emitOpenAIResponseMeta,
    repeatedToolCallState,
    maxConsecutiveIdenticalToolRounds,
    sendTurnState,
    touchProjectUsageByThread,
    continuityRuntime,
    runPostTurnTasks,
    projectFolder,
    userMessage,
    turnToolResults,
    mode,
    memoryCompressionEnabled,
    memoryCompressionThreshold,
    memoryCompressionCooldownMs,
    memoryCompressionMaxPerHour,
    memoryCompressionMinNewLogs,
    loop,
    isAbortError,
    assistantFinalPhase,
    assistantCommentaryPhase,
    buildChatUsagePayload,
    emitUsageEvent,
    emitReasoningDone,
    updateOpenAIContinuationContext,
    resolveOpenAIContinuationPersistence,
    recordRepeatedToolCallBatch,
    commitFailureTurn,
    finalizeRoundWithoutTools,
    buildAssistantToolUseMessage,
    createStreamWithTools,
    detectTextualApprovalRequestWithoutToolCall,
    allowBlankAssistantCompletion: Boolean(turnOptions?.planAction),
    asTokenCount,
    pushUniqueRuntimeValue,
  })
  currentOpenAIRequestContext = modelRound.nextOpenAIRequestContext
  if (modelRound.shouldBreakRoundLoop) {
    emitTurnRuntimeDiagnostics()
    return {
      shouldBreakRoundLoop: true,
      latestOpenAICompactionId: nextLatestOpenAICompactionId,
      currentOpenAIRequestContext,
      currentProviderRequestContext,
      stepSequence,
      consecutiveErrorRounds,
      hostFullAccessApprovedForTurn,
      moaPreflightRepairRetryUsed,
      moaPendingPreflightRepairRetryAttempt,
    }
  }

  const toolCalls = Array.isArray(modelRound.toolCalls) ? modelRound.toolCalls : []
  if (toolCalls.length > 0) {
    sendTurnState('tools_pending', {
      status: 'tools_pending',
      label: 'tools pending',
      round,
      count: toolCalls.length,
      toolNames: toolCalls.map((tc) => String(tc?.name || '').trim()).filter(Boolean),
    })
  }
  const roundState = await runToolCallBatchForRound({
    toolCalls,
    loop,
    sender,
    wid,
    settings,
    mode,
    permissionMode,
    projectFolder,
    providerId,
    model: model ?? '',
    promptBudgetProfile,
    apiKey,
    providerRuntimeSettings,
    orchestratorIntent: turnOptions?.orchestratorIntent,
    delegationSelectionIntent: turnOptions?.delegationSelectionIntent,
    moaRoles,
    moaPolicy,
    moaBudgetPolicy,
    agentSettings,
    activeThreadId,
    activeTurnId,
    history,
    turnToolResults,
    turnReasoningSegments,
    providerToolExecutionContext,
    toolExecutionMap,
    activeToolDefinitions,
    tools,
    inspectedFilePathsThisTurn,
    errorDiagnostics,
    send,
    persistTimelineEvent,
    sendTurnState,
    emitTurnRuntimeDiagnostics,
    requestFanoutConfirmation,
    turnStartedAt,
    stepSequence,
    consecutiveErrorRounds,
    hostFullAccessApprovedForTurn,
    moaPreflightRepairRetryUsed,
    moaPendingPreflightRepairRetryAttempt,
    moaRetryState,
    maxConsecutiveErrorRounds,
    getApiKey,
    getCachedCapabilities: getCachedModelCapabilities,
    helpers: toolBatchHelpers,
  })

  return {
    shouldBreakRoundLoop: roundState.shouldBreakRoundLoop,
    latestOpenAICompactionId: nextLatestOpenAICompactionId,
    currentOpenAIRequestContext,
    currentProviderRequestContext,
    stepSequence: roundState.stepSequence,
    consecutiveErrorRounds: roundState.consecutiveErrorRounds,
    hostFullAccessApprovedForTurn: roundState.hostFullAccessApprovedForTurn,
    moaPreflightRepairRetryUsed: roundState.moaPreflightRepairRetryUsed,
    moaPendingPreflightRepairRetryAttempt: roundState.moaPendingPreflightRepairRetryAttempt,
    questionUserRequest: roundState.questionUserRequest || null,
  }
}
