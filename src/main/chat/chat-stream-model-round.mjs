import {
  executeProviderModelStream,
  finalizeProviderModelRound,
} from './chat-stream-model-step.mjs'

export async function runProviderModelRound({
  providerId = '',
  apiKey = '',
  history = [],
  options = {},
  providerRuntimeSettings = null,
  activeProjectId = '',
  activeThreadId = '',
  activeTurnId = '',
  activeAssistantMessageId = '',
  tools = {},
  openAIRequestContextForRound = undefined,
  providerRequestContextForRound = undefined,
  round = 0,
  model = '',
  send = () => {},
  persistTimelineEvent = () => {},
  sendNotice = () => {},
  turnStartedAt = 0,
  errorDiagnostics = {},
  rollingUsage = {},
  modelContext = {},
  promptOccupancyEstimateTokens = 0,
  promptOccupancyEstimateConfidence = 'rough_estimate',
  promptOccupancyEstimateMethod = 'history_estimate',
  turnReasoningSegments = [],
  openAIContinuityEnabled = false,
  emitOpenAIResponseMeta = () => {},
  repeatedToolCallState = null,
  maxConsecutiveIdenticalToolRounds = 3,
  sendTurnState = () => {},
  touchProjectUsageByThread = () => {},
  continuityRuntime = null,
  runPostTurnTasks = () => {},
  projectFolder = '',
  userMessage = '',
  turnToolResults = [],
  mode = '',
  memoryCompressionEnabled = false,
  memoryCompressionThreshold = 0,
  memoryCompressionCooldownMs = 0,
  memoryCompressionMaxPerHour = 0,
  memoryCompressionMinNewLogs = 0,
  loop,
  isAbortError = () => false,
  assistantFinalPhase = '',
  assistantCommentaryPhase = '',
  buildChatUsagePayload = () => null,
  emitUsageEvent = () => {},
  emitReasoningDone = () => {},
  updateOpenAIContinuationContext = (context) => context,
  resolveOpenAIContinuationPersistence = () => ({}),
  recordRepeatedToolCallBatch = () => ({ blocked: false }),
  commitFailureTurn = null,
  finalizeRoundWithoutTools = () => {},
  buildAssistantToolUseMessage = () => ({}),
  createStreamWithTools,
  detectTextualApprovalRequestWithoutToolCall = () => false,
  allowBlankAssistantCompletion = false,
  asTokenCount = (value) => Number(value || 0) || 0,
  pushUniqueRuntimeValue = () => {},
} = {}) {
  const streamResult = await executeProviderModelStream({
    providerId,
    apiKey,
    history,
    options,
    providerRuntimeSettings,
    projectFolder,
    activeProjectId,
    activeThreadId,
    activeTurnId,
    activeAssistantMessageId,
    mode,
    tools,
    openAIRequestContextForRound,
    providerRequestContextForRound,
    round,
    model: model ?? '',
    send,
    persistTimelineEvent,
    sendNotice,
    buildChatUsagePayload,
    modelContext,
    promptOccupancyEstimateTokens,
    promptOccupancyEstimateConfidence,
    promptOccupancyEstimateMethod,
    rollingUsage,
    createStreamWithTools,
  })

  return finalizeProviderModelRound({
    streamResult,
    errorDiagnostics,
    turnStartedAt,
    rollingUsage,
    asTokenCount,
    buildChatUsagePayload,
    emitUsageEvent,
    send,
    persistTimelineEvent,
    modelContext,
    promptOccupancyEstimateTokens,
    promptOccupancyEstimateConfidence,
    promptOccupancyEstimateMethod,
    round,
    emitReasoningDone,
    activeThreadId,
    activeTurnId,
    activeAssistantMessageId,
    providerId,
    model: model ?? '',
    turnReasoningSegments,
    openAIContinuityEnabled,
    openAIRequestContextForRound,
    providerRequestContextForRound,
    updateOpenAIContinuationContext,
    emitOpenAIResponseMeta,
    resolveOpenAIContinuationPersistence,
    repeatedToolCallState,
    recordRepeatedToolCallBatch,
    commitFailureTurn,
    maxConsecutiveIdenticalToolRounds,
    pushUniqueRuntimeValue,
    sendNotice,
    sendTurnState,
    loop,
    finalizeRoundWithoutTools,
    touchProjectUsageByThread,
    continuityRuntime,
    runPostTurnTasks,
    projectFolder,
    userMessage,
    turnToolResults,
    mode,
    memoryCompressionEnabled,
    memoryCompressionThreshold,
    memoryCompressionCooldownMs,
    memoryCompressionMaxPerHour,
    memoryCompressionMinNewLogs,
    apiKey,
    isAbortError,
    assistantFinalPhase,
    assistantCommentaryPhase,
    buildAssistantToolUseMessage,
    history,
    detectTextualApprovalRequestWithoutToolCall,
    allowBlankAssistantCompletion,
  })
}
